using System.Net;
using System.Text;

namespace HackWizard.Core.Reports;

internal static class Html
{
    public static string E(string? s) => WebUtility.HtmlEncode(s ?? "");

    public static string Page(string title, string body) => new StringBuilder()
        .Append("<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">")
        .Append("<title>").Append(E(title)).Append("</title><style>")
        .Append("body{font-family:Segoe UI,Arial,sans-serif;max-width:1000px;margin:24px auto;padding:0 16px;line-height:1.5;color:#1b1b1b;background:#fff}")
        .Append("@media(prefers-color-scheme:dark){body{background:#1e1e1e;color:#eee}th{background:#333!important}td,th{border-color:#555!important}.box{background:#2a2a2a!important}}")
        .Append("table{border-collapse:collapse;width:100%;margin:12px 0}td,th{border:1px solid #ccc;padding:6px 8px;text-align:left;vertical-align:top}th{background:#f2f2f2}")
        .Append(".Supported{color:#0a7d27;font-weight:600}.Partial{color:#b26a00;font-weight:600}.Unsupported{color:#c62828;font-weight:600}.Info{color:#555}")
        .Append(".box{background:#f6f8fa;border-left:4px solid #0067c0;padding:10px 14px;margin:12px 0}.warn{border-left-color:#b26a00}.danger{border-left-color:#c62828}")
        .Append("code,kbd{background:rgba(127,127,127,.15);padding:1px 4px;border-radius:3px}.shot{border:2px dashed #999;padding:18px;text-align:center;color:#888;margin:8px 0}")
        .Append("</style></head><body><h1>").Append(E(title)).Append("</h1>").Append(body)
        .Append("<hr><p style=\"font-size:12px;color:#888\">Generated by HackWizard (open source, MIT) ").Append(DateTime.Now.ToString("yyyy-MM-dd HH:mm")).Append("</p></body></html>")
        .ToString();
}
